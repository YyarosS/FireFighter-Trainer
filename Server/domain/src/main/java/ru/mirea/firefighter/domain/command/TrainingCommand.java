package ru.mirea.firefighter.domain.command;

import java.time.Instant;

/**
 * Команда сервера VR-клиенту.
 *
 * <p>Архитектура «сервер-авторитет»: клиент присылает только факты
 * (события телеметрии), а решения оформляются сервером в виде команд.
 * Иерархия запечатана ({@code sealed}) — набор команд закрыт, и
 * клиентский код обязан обработать каждый вариант (исчерпывающий разбор),
 * что исключает появление «неизвестной команды».</p>
 *
 * <p>Поле {@code sequence} монотонно растёт в рамках сеанса: клиент
 * запрашивает команды начиная с последней полученной, поэтому потери
 * сообщений при обрыве связи не приводят к рассинхронизации.</p>
 */
public sealed interface TrainingCommand
        permits StartScenarioCommand, UpdateEnvironmentCommand, ShowHintCommand, EndSessionCommand {

    /** Порядковый номер команды внутри сеанса, начиная с 1. */
    long sequence();

    /** Момент выдачи команды. */
    Instant issuedAt();

    /** Строковое имя типа — для сериализации в REST/JSON. */
    String type();
}