package ru.mirea.firefighter.domain.model.vo;

/**
 * Состояние сеанса тренировки.
 *
 * <p>Явный перечислимый тип вместо строковых статусов: переходы между
 * состояниями контролирует агрегат {@code TrainingSession}.</p>
 */
public enum SessionStatus {

    /** Тренировка идёт: события принимаются, команды выдаются. */
    RUNNING,

    /** Тренировка завершена: оценка рассчитана, новые события запрещены. */
    FINISHED
}